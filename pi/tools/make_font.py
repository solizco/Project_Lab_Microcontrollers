#!/usr/bin/env python3
"""Bake pygame's default font (what Finn's connect4.py uses via Font(None, size))
into src/font_data.h as 8-bit alpha glyphs, so the C++ UI matches his menu
without needing pygame or FreeType on the Pi."""
import os, sys
os.environ["SDL_VIDEODRIVER"] = "dummy"; os.environ["PYGAME_HIDE_SUPPORT_PROMPT"] = "1"
import pygame
pygame.font.init()
SIZES = [("TITLE", 76), ("ITEM", 50), ("LABEL", 32), ("BIG", 72), ("TABLE", 34), ("SMALL", 26)]
out = ["// GENERATED by tools/make_font.py from pygame's freesansbold.ttf. Do not edit.",
       "// Included by gfx.cpp ONLY (it is large). Order must match enum FontId in gfx.h.",
       "#pragma once", "#include <stdint.h>", ""]
data_all = []
for name, size in SIZES:
    f = pygame.font.Font(None, size)
    surfs = [f.render(chr(c), True, (255, 255, 255), (0, 0, 0)) for c in range(32, 127)]
    h = max([f.get_height()] + [s.get_height() for s in surfs])   # pad every glyph to one height
    widths, offsets, blob = [], [], bytearray()
    for s in surfs:
        w = s.get_width()
        cell = pygame.Surface((w, h)); cell.fill((0, 0, 0)); cell.blit(s, (0, 0))
        raw = pygame.image.tostring(cell, "RGB")
        offsets.append(len(blob)); widths.append(w)
        blob += bytes(raw[i * 3] for i in range(w * h))
    out.append(f"static const uint8_t FONT_{name}_DATA[{len(blob)}] = {{")
    for i in range(0, len(blob), 40):
        out.append("  " + ",".join(str(b) for b in blob[i:i + 40]) + ",")
    out.append("};")
    out.append(f"static const uint16_t FONT_{name}_W[95] = {{{','.join(map(str, widths))}}};")
    out.append(f"static const uint32_t FONT_{name}_OFF[95] = {{{','.join(map(str, offsets))}}};")
    data_all.append((name, size, h))
out.append("")
out.append("static const FontData FONTS[] = {")
for name, size, h in data_all:
    out.append(f"  {{ {size}, {h}, FONT_{name}_DATA, FONT_{name}_W, FONT_{name}_OFF }},")
out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("fonts:", data_all)
